/** Helpers for dates relative to current date (YYYY-MM-DD) */
export function offsetDateIso(daysOffset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + daysOffset);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

export function offsetDateTimeIso(daysOffset: number, timeStr = '08:00'): string {
  return `${offsetDateIso(daysOffset)}T${timeStr}`;
}

